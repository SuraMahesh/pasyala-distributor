// An assistant reply laid out as a printable report (the PDF comes from the browser's Print / Save PDF).
import type { Settings } from '@pjd/shared'
import { Markdown } from './Markdown'

export default function AssistantReport({ settings, question, reply, askedBy, date }: {
  settings?: Settings
  question: string
  reply: string
  askedBy: string
  date: string
}) {
  return (
    <div className="print-area card mx-auto max-w-4xl bg-white p-4 text-[12px] text-stone-900 sm:p-6 sm:text-[13px] md:p-10">
      <div className="text-center">
        <h2 className="text-lg font-bold tracking-tight sm:text-xl">{settings?.name ?? 'Pasyala Janith Distributor'}</h2>
        {settings?.address && <p className="text-stone-600">{settings.address}</p>}
        {settings && <p className="text-stone-600">{[settings.phone && `Tel: ${settings.phone}`, settings.email && `Email: ${settings.email}`].filter(Boolean).join(' · ')}</p>}
        <p className="mt-3 text-base font-bold tracking-[0.2em] sm:mt-4 sm:text-lg">ASSISTANT REPORT</p>
      </div>
      <dl className="mt-4 grid grid-cols-[90px_1fr] gap-y-1 border-y border-stone-200 py-2 sm:mt-5">
        <dt className="font-semibold">Date</dt>
        <dd>{date}</dd>
        {askedBy && (
          <>
            <dt className="font-semibold">Asked by</dt>
            <dd>{askedBy}</dd>
          </>
        )}
        <dt className="font-semibold">Question</dt>
        <dd className="whitespace-pre-wrap">{question || '—'}</dd>
      </dl>
      <div className="mt-4 [&_.table]:w-full [&_table]:text-[inherit] [&_.text-sm]:text-[inherit]">
        <Markdown text={reply} />
      </div>
      <p className="mt-6 border-t border-stone-200 pt-2 text-[11px] text-stone-500">
        Figures as recorded in the ERP when the question was asked. Generated by the ERP assistant.
      </p>
    </div>
  )
}
